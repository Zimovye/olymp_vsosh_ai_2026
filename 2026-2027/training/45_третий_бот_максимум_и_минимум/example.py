# Маленький готовый пример для пяти объектов.
y =  [1, 0, 1, 0, 1]
h1 = [1, 1, 0, 1, 0]
h2 = [1, 0, 0, 0, 1]

max_correct = 0
min_correct = 0

for i in range(len(y)):
    if h1[i] == h2[i]:
        # Два одинаковых голоса уже нельзя перебить третьим голосом.
        if h1[i] == y[i]:
            max_correct += 1
            min_correct += 1
            print("Объект", i + 1, "— ответ зафиксирован и верен")
        else:
            print("Объект", i + 1, "— ответ зафиксирован и неверен")
    else:
        # При споре первых двух ботов h3 можно выбрать верным или неверным.
        max_correct += 1
        print("Объект", i + 1, "— h1 и h2 спорят")
        print("  Для максимума выбираем h3 =", y[i])
        print("  Для минимума выбираем h3 =", 1 - y[i])

print("Максимальное число верных ответов:", max_correct)
print("Минимальное число верных ответов:", min_correct)
