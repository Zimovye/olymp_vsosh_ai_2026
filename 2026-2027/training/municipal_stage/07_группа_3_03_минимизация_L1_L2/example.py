# Учебный пример группы III, № 3: исходные данные заменены маленьким набором.
from fractions import Fraction

y = [7, 1, 6, 2]
print("Истинные значения:", y)

# Таблица помогает увидеть, как выбор общего предсказания меняет ошибки.
# Это иллюстрация: оптимальное c в задаче может быть и дробным.
print("c | L1 | L2")
for c in range(1, 8):
    l1 = 0
    l2 = 0
    for value in y:
        l1 += abs(value - c)
        l2 += (value - c) ** 2
    print(c, "|", l1, "|", l2)

y_sorted = sorted(y)
n = len(y_sorted)
print("После сортировки:", y_sorted)

# При двух средних элементах нужен левый: условие требует наименьшее c.
# Для нечётного количества эта же запись выбирает единственный средний элемент.
c1 = y_sorted[(n - 1) // 2]

# Среднее может оказаться дробным; сохраняем его точно, без округления.
c2 = Fraction(sum(y), n)

print("Предсказание c1 для L1:", c1)
print("Предсказание c2 для L2:", c2)
