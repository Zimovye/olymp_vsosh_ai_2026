# Учебный пример: разница 2 вместо 110 из исходной задачи.
difference = 2
print("Нужная разница:", difference)

# a делит положительную разницу, поэтому a не больше difference.
# a = 1 не подходит: степень равна 1, а произведение не меньше 1.
for a in range(2, difference + 1):
    b = 1

    # Разница не уменьшается при росте b: после превышения искать незачем.
    while a**b - a * b <= difference:
        correct = a**b  # ** — степень, как и хотел Дима.
        model = a * b  # * — умножение, которое выполнила модель.

        if correct - model == difference:
            print("Найдены числа: a =", a, "b =", b)
            print("Правильный результат (степень):", correct)
            print("Результат модели (умножение):", model)
            print("Проверка разницы:", correct - model)
            print("Ответ модели:", model)

        b += 1
