p1, p2, p3, p4, p5, p6, p7 = map(int, input().split())

# У всех вероятностей знаменатель 100 * 100 * 100, поэтому сравниваем числители.
p000 = p1 * p2 * p4
p001 = p1 * p2 * (100 - p4)
p010 = p1 * (100 - p2) * p5
p011 = p1 * (100 - p2) * (100 - p5)
p100 = (100 - p1) * p3 * p6
p101 = (100 - p1) * p3 * (100 - p6)
p110 = (100 - p1) * (100 - p3) * p7
p111 = (100 - p1) * (100 - p3) * (100 - p7)

paths = [
    (p000, "000"),
    (p001, "001"),
    (p010, "010"),
    (p011, "011"),
    (p100, "100"),
    (p101, "101"),
    (p110, "110"),
    (p111, "111"),
]

print("Числители вероятностей до сортировки; общий знаменатель — 1000000:")
for probability, code in paths:
    print(code, ":", probability)

# При равных числителях сортировка пар сравнит сами строки путей.
paths.sort()

print("Ответ:")
for probability, code in paths:
    print(code)
