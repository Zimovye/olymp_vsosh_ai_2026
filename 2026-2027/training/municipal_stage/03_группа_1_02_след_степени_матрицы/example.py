# Учебное изменение исходной задачи: ищем след A^5 вместо A^20.
# A = (1 1)
#     (1 0)
power = 5

# Начальная матрица — уже A^1, поэтому цикл начнётся со второй степени.
p, q, r, s = 1, 1, 1, 0
print("Степень:", 1, "Строки матрицы:", (p, q), (r, s), "След:", p + s)

for k in range(2, power + 1):
    # Все новые клетки считаем из старой матрицы и только потом обновляем её.
    new_p = p + q
    new_q = p
    new_r = r + s
    new_s = r

    p, q, r, s = new_p, new_q, new_r, new_s
    print("Степень:", k, "Строки матрицы:", (p, q), (r, s), "След:", p + s)

print("Ответ:", p + s)
