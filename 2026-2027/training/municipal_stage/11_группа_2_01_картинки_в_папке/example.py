# Учебные данные: 12 картинок, 10 ответов «да» про кошку и 11 про собаку.
total = 12
yes_cat = 10
yes_dog = 11

# Три типа представлены поровну, поэтому делим общее число на три.
per_type = total // 3
no_cat = total - yes_cat
no_dog = total - yes_dog

print("Картинок каждого типа:", per_type)
print("Ответов «нет» про кошку:", no_cat)
print("Ответов «нет» про собаку:", no_dog)
print("Всего ответов «нет»:", no_cat + no_dog)

# В этих данных все «нет» помещаются на разных картинках с обоими животными.
# Так удаляется как можно больше таких картинок; остальные получат «да/да».
min_left = per_type - no_cat - no_dog
print("Минимум оставшихся:", min_left)
